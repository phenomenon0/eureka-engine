#!/usr/bin/env python3
# tools/gen_unicode_data.py — emit qwen35_unicode_data.inc from the reference
# Unicode tables in llama.cpp's src/unicode-data.cpp.
#
# The Qwen3.5 pre-tokenizer needs the same Unicode category / whitespace /
# lowercase facts llama.cpp uses; those facts are pure Unicode data, so we
# vendor them (generated) rather than re-deriving (which could differ by
# Unicode version). Provenance: ~/llama.cpp/src/unicode-data.cpp.
#
# usage: gen_unicode_data.py [path/to/unicode-data.cpp] [-o out.inc]
import re
import sys
import os

src = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else os.path.expanduser("~/llama.cpp/src/unicode-data.cpp")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "qwen35_unicode_data.inc")
if "-o" in sys.argv:
    out = sys.argv[sys.argv.index("-o") + 1]

text = open(src, encoding="utf-8").read()

def block(name, op="{"):
    i = text.index(name)
    i = text.index(op, i) + 1
    j = text.index("};", i)
    return text[i:j]

# ranges flags: {0x000000, 0x0080},
flag_pairs = re.findall(r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}", block("unicode_ranges_flags"))
flags = [(int(a, 16), int(b, 16)) for a, b in flag_pairs]

ws = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", block("unicode_set_whitespace"))]
lower = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}", block("unicode_map_lowercase"))]
upper = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}", block("unicode_map_uppercase"))]

assert flags and flags[0][0] == 0, "flags table must start at 0"
assert ws and lower and upper

def arr(name, typ, items, fmt):
    s = [f"static const {typ} {name}[] = {{"]
    line = "  "
    for it in items:
        piece = fmt(it) + ", "
        if len(line) + len(piece) > 100:
            s.append(line.rstrip())
            line = "  "
        line += piece
    if line.strip():
        s.append(line.rstrip())
    s.append("};")
    return "\n".join(s)

with open(out, "w") as f:
    f.write("// generated by tools/gen_unicode_data.py from llama.cpp src/unicode-data.cpp — do not edit\n")
    f.write("// Unicode category/whitespace/case facts for the Qwen3.5 pre-tokenizer.\n")
    f.write("#ifndef QWEN35_UNICODE_DATA_INC\n#define QWEN35_UNICODE_DATA_INC\n\n")
    f.write("// start, flags (last codepoint = next start - 1). Category bits match\n")
    f.write("// llama.cpp unicode_cpt_flags: 1=undef 2=N 4=L 8=Z 0x10=M 0x20=P 0x40=S 0x80=C\n")
    f.write("// 0x100=whitespace 0x200=lower 0x400=upper.\n")
    f.write(arr("uni_flags_start", "uint32_t", flags, lambda x: f"0x{x[0]:X}") + "\n")
    f.write(arr("uni_flags_val", "uint16_t", flags, lambda x: f"0x{x[1]:04X}") + "\n")
    f.write(f"static const int uni_flags_n = {len(flags)};\n\n")

    f.write("static const uint32_t uni_ws[] = { " + ", ".join(f"0x{x:X}" for x in ws) + " };\n")
    f.write(f"static const int uni_ws_n = {len(ws)};\n\n")

    f.write("// ascending by first, for binary search\n")
    f.write(arr("uni_lower_first", "uint32_t", lower, lambda x: f"0x{x[0]:X}") + "\n")
    f.write(arr("uni_lower_second", "uint32_t", lower, lambda x: f"0x{x[1]:X}") + "\n")
    f.write(f"static const int uni_lower_n = {len(lower)};\n\n")

    f.write(arr("uni_upper_first", "uint32_t", upper, lambda x: f"0x{x[0]:X}") + "\n")
    f.write(arr("uni_upper_second", "uint32_t", upper, lambda x: f"0x{x[1]:X}") + "\n")
    f.write(f"static const int uni_upper_n = {len(upper)};\n\n")

    # inline lookups
    f.write("""static inline uint16_t uni_flags_from_cpt(uint32_t cpt) {
  int lo = 0, hi = uni_flags_n - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    if (cpt < uni_flags_start[mid]) hi = mid - 1;
    else if (mid + 1 < uni_flags_n && cpt >= uni_flags_start[mid + 1]) lo = mid + 1;
    else return uni_flags_val[mid];
  }
  return 0x0001; // UNDEFINED
}

static inline int uni_is_ws(uint32_t cpt) {
  int lo = 0, hi = uni_ws_n - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    if (cpt < uni_ws[mid]) hi = mid - 1;
    else if (cpt > uni_ws[mid]) lo = mid + 1;
    else return 1;
  }
  return 0;
}

static inline uint32_t uni_tolower(uint32_t cpt) {
  int lo = 0, hi = uni_lower_n - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    if (cpt < uni_lower_first[mid]) hi = mid - 1;
    else if (cpt > uni_lower_first[mid]) lo = mid + 1;
    else return uni_lower_second[mid];
  }
  return cpt;
}

// full per-codepoint flags incl. whitespace + case bits (llama.cpp
// unicode_cpt_flags_array, without the NFD bit which BPE never reads)
static inline uint16_t uni_flags_full(uint32_t cpt) {
  uint16_t fl = uni_flags_from_cpt(cpt);
  if (uni_is_ws(cpt)) fl |= 0x0100;
  {
    int lo = 0, hi = uni_lower_n - 1;
    while (lo <= hi) {
      int mid = (lo + hi) >> 1;
      if (cpt < uni_lower_first[mid]) hi = mid - 1;
      else if (cpt > uni_lower_first[mid]) lo = mid + 1;
      else { fl |= 0x0200; break; }
    }
  }
  {
    int lo = 0, hi = uni_upper_n - 1;
    while (lo <= hi) {
      int mid = (lo + hi) >> 1;
      if (cpt < uni_upper_first[mid]) hi = mid - 1;
      else if (cpt > uni_upper_first[mid]) lo = mid + 1;
      else { fl |= 0x0400; break; }
    }
  }
  return fl;
}

#endif
""")

print(f"wrote {out}: flags={len(flags)} ws={len(ws)} lower={len(lower)} upper={len(upper)}")
