#!/usr/bin/env python3
"""The format registry: tools/formats.tsv.

usage: formats.py gen            write host/llb_formats.h
       formats.py check [COMP]   fail loudly if any consumer disagrees

Importers use FMT (name -> fm), ROWS (name -> row). check compares the header,
gguf_convert.GGML_TYPES, every literal "NAME": n / strcmp(t, "NAME")) return n
map left in tools/, and (with COMP, a patched comp.ts) the cuModuleGetFunction
table plus host/llb_host.c's `fm == n ? host_var` select.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / "tools" / "formats.tsv"
HDR = ROOT / "host" / "llb_formats.h"


def load():
    rows = {}
    for ln in TSV.read_text().splitlines():
        if ln.startswith("#") or not ln.strip():
            continue
        n, g, fm, bb, be, fn, hv = ln.split("\t")
        rows[n] = dict(
            ggml=None if g == "-" else int(g),
            fm=int(fm),
            bytes=int(bb),
            elems=int(be),
            fn=None if fn == "-" else fn,
            var=None if hv == "-" else hv,
        )
    fms = [r["fm"] for r in rows.values()]
    assert len(set(fms)) == len(fms) and max(fms) < 16, "fm must be unique and < 16"
    return rows


ROWS = load()
FMT = {n: r["fm"] for n, r in ROWS.items()}


def header():
    out = [
        "// generated by tools/formats.py from tools/formats.tsv: do not edit",
        "#ifndef LLB_FORMATS_H",
        "#define LLB_FORMATS_H",
    ]
    for n, r in ROWS.items():
        out.append(f"#define LLB_FM_{n} {r['fm']}")
    out.append("// X(name, fm, block bytes, block elements)")
    out.append(
        "#define LLB_FORMATS(X) "
        + " ".join(
            f"X({n}, {r['fm']}, {r['bytes']}, {r['elems']})" for n, r in ROWS.items()
        )
    )
    rb = "".join(
        f"(fm) == {r['fm']} ? (c) / {r['elems']} * {r['bytes']} : "
        for r in ROWS.values()
    )
    out.append("// row bytes of a cols-wide row; 0 for an unknown fm")
    out.append(f"#define LLB_FM_RB(fm, c) ({rb}0)")
    out.append("#endif")
    return "\n".join(out) + "\n"


def check(comp=None):
    bad = []
    if not HDR.exists() or HDR.read_text() != header():
        bad.append(f"{HDR} stale: run tools/formats.py gen")
    sys.path.insert(0, str(ROOT / "tools"))
    from gguf_convert import GGML_TYPES

    for gid, (n, be, bb) in GGML_TYPES.items():
        r = ROWS.get(n)
        if r and (r["ggml"], r["elems"], r["bytes"]) != (gid, be, bb):
            bad.append(f"gguf_convert {n}: ({gid},{be},{bb}) vs registry")
    # fm maps left in tools/: FMT = {...} dicts and the twin's strcmp chain
    for f in sorted((ROOT / "tools").glob("*.py")) + [ROOT / "tools" / "qwen35_engine.c"]:
        if f.name == "formats.py":
            continue
        t = f.read_text()
        pairs = [p for d in re.findall(r"FMT\s*=\s*\{([^}]*)\}", t)
                 for p in re.findall(r'"(\w+)"\s*:\s*(\d+)', d)]
        pairs += re.findall(r'strcmp\(t, "(\w+)"\)\) return (\d+)', t)
        for n, v in pairs:
            if FMT.get(n) != int(v):
                bad.append(f"{f.name}: {n} = {v}, registry {FMT.get(n)}")
    if comp:
        src = Path(comp).read_text()
        for n, r in ROWS.items():
            if (
                r["fn"]
                and f'cuModuleGetFunction(&{r["var"]}, gpu_lib, "{r["fn"]}")' not in src
            ):
                bad.append(f"comp.ts: no {r['var']} = {r['fn']} ({n})")
        host = (ROOT / "host" / "llb_host.c").read_text()
        var = {r["var"]: r["fm"] for r in ROWS.values() if r["var"]}
        for v, k in re.findall(r"fm == (\d+) \? (gpu_\w+)", host):
            if var.get(k) != int(v):
                bad.append(f"llb_host.c: fm == {v} -> {k}, registry {var.get(k)}")
    if bad:
        raise SystemExit("formats check FAILED:\n  " + "\n  ".join(bad))
    print(
        f"formats check PASS: {len(ROWS)} formats" + (" + comp.ts/host" if comp else "")
    )


if __name__ == "__main__":
    a = sys.argv[1:]
    if a == ["gen"]:
        HDR.write_text(header())
        print(f"wrote {HDR}")
    elif a[:1] == ["check"] and len(a) <= 2:
        check(a[1] if len(a) == 2 else None)
    else:
        raise SystemExit(__doc__)
