// test_metrics.c: unit tests for metrics.c (percentile math, histogram buckets,
// the sliding window, the timings block, the Prometheus text).
// cc -std=c11 -O2 -Wall -Wextra tools/metrics/test_metrics.c tools/metrics/metrics.c -lpthread -lm
// Expected percentile values are numpy.percentile(..., method="linear") results
// (tools/metrics/numpy_ref.py prints them for the receipt).
#define _POSIX_C_SOURCE 200809L
#include "metrics.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int fails, checks;

#define CHECK(c, ...) do { checks++; if (!(c)) { fails++; printf("FAIL %s:%d: ", __FILE__, __LINE__); printf(__VA_ARGS__); printf("\n"); } } while (0)

static int near(double a, double b) { return fabs(a - b) <= 1e-12 * (1 + fabs(b)); }

static void t_percentile(void) {
    double one[] = {7};
    CHECK(near(llb_percentile(one, 1, .5), 7), "single");
    CHECK(near(llb_percentile(one, 1, .99), 7), "single p99");
    CHECK(isnan(llb_percentile(one, 0, .5)), "empty is NaN");
    double a[] = {1, 2, 3, 4};
    CHECK(near(llb_percentile(a, 4, .5), 2.5), "p50 of 1..4 = %g", llb_percentile(a, 4, .5));
    CHECK(near(llb_percentile(a, 4, .9), 3.7), "p90 of 1..4 = %g", llb_percentile(a, 4, .9));
    CHECK(near(llb_percentile(a, 4, 0), 1), "p0");
    CHECK(near(llb_percentile(a, 4, 1), 4), "p100");
    double b[100];
    for (int i = 0; i < 100; i++) b[i] = i + 1;   // 1..100
    CHECK(near(llb_percentile(b, 100, .5), 50.5), "p50 1..100 = %g", llb_percentile(b, 100, .5));
    CHECK(near(llb_percentile(b, 100, .95), 95.05), "p95 1..100 = %.17g", llb_percentile(b, 100, .95));
    CHECK(near(llb_percentile(b, 100, .99), 99.01), "p99 1..100 = %.17g", llb_percentile(b, 100, .99));
    double c[] = {0.010, 0.012, 0.013, 0.020, 0.100};
    CHECK(near(llb_percentile(c, 5, .9), 0.068), "p90 skew = %.17g", llb_percentile(c, 5, .9));
    CHECK(near(llb_percentile(c, 5, .5), 0.013), "p50 skew");
}

static const char *line(const char *txt, const char *prefix) {
    for (const char *p = txt; p && *p;) {
        if (!strncmp(p, prefix, strlen(prefix))) return p;
        p = strchr(p, '\n');
        if (p) p++;
    }
    return NULL;
}

static double val(const char *txt, const char *prefix) {
    const char *l = line(txt, prefix);
    return l ? strtod(l + strlen(prefix), NULL) : NAN;
}

// one synthetic request with exact clocks: arrive 0, start +a, tokens at given offsets, end
static void fake(double base, double start, const double *tok, int n, int prompt, int cached, const char *outcome) {
    llb_req r;
    llb_req_begin(&r);
    r.t_arrive = base;
    r.t_start = base + start;
    r.prompt_n = prompt;
    r.cached_n = cached;
    for (int i = 0; i < n; i++) llb_req_token_at(&r, base + tok[i]);
    llb_req_end(&r, "generate", outcome);
}

static void t_aggregates(void) {
    llb_metrics_reset();
    // integer base + dyadic offsets: every difference below is exact in binary
    double base = floor(llb_now()) - 100;
    // req 1: queue 1/128 s, first token at 1/8 s, then 3 tokens 1/64 s apart
    double t1[] = {.125, .140625, .15625, .171875};
    fake(base, .0078125, t1, 4, 10, 0, "ok");
    // req 2: 6 prompt tokens, 4 cached (partial); ITLs 1/32 s and exactly 0.5 s (a bucket edge)
    double t2[] = {.0625, .09375, .59375};
    fake(base, .00390625, t2, 3, 6, 4, "ok");
    // req 3: retained full hit, no tokens generated by the engine
    llb_req r;
    llb_req_begin(&r);
    llb_req_start(&r, 8, 8);
    llb_req_end(&r, "generate", "retained");
    llb_req_spec(&r, 0, 0);
    size_t n;
    char *txt = llb_metrics_render(&n);
    CHECK(txt && n == strlen(txt), "render length");
    CHECK(val(txt, "llb_requests_total{mode=\"generate\",outcome=\"ok\"} ") == 2, "ok count");
    CHECK(val(txt, "llb_requests_total{mode=\"generate\",outcome=\"retained\"} ") == 1, "retained count");
    CHECK(val(txt, "llb_generated_tokens_total ") == 7, "gen tokens");
    CHECK(val(txt, "llb_prompt_tokens_total ") == 24, "prompt tokens");
    CHECK(val(txt, "llb_prefill_tokens_total ") == 12, "prefilled = 10 + 2 = %g", val(txt, "llb_prefill_tokens_total "));
    CHECK(val(txt, "llb_cache_tokens_total ") == 12, "cached tokens");
    CHECK(val(txt, "llb_cache_requests_total{result=\"hit\"} ") == 1, "hit");
    CHECK(val(txt, "llb_cache_requests_total{result=\"partial\"} ") == 1, "partial");
    CHECK(val(txt, "llb_cache_requests_total{result=\"miss\"} ") == 1, "miss");
    CHECK(val(txt, "llb_decode_steps_total ") == 5, "decode steps 3+2");
    // ITLs: 3 x .015625, .03125, .5 -> le is inclusive: le=.02 -> 3, le=.04 -> 4, le=.5 -> 5 (edge)
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.015\"} ") == 0, "itl le .015");
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.02\"} ") == 3, "itl le .02 = %g",
          val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.02\"} "));
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.03\"} ") == 3, "itl le .03");
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.04\"} ") == 4, "itl le .04");
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.25\"} ") == 4, "itl le .25");
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"0.5\"} ") == 5, "itl le .5 (edge inclusive)");
    CHECK(val(txt, "llb_inter_token_latency_seconds_bucket{le=\"+Inf\"} ") == 5, "itl +Inf");
    CHECK(val(txt, "llb_inter_token_latency_seconds_count ") == 5, "itl count");
    CHECK(near(val(txt, "llb_inter_token_latency_seconds_sum "), .578125), "itl sum %.17g", val(txt, "llb_inter_token_latency_seconds_sum "));
    // window: p50 = .015625 ; p90 = .03125 + .6*(.5-.03125) = .3125 (numpy_ref.py)
    CHECK(near(val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.5\"} "), .015625), "itl p50");
    CHECK(fabs(val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.9\"} ") - .3125) < 1e-9, "itl p90 %.17g",
          val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.9\"} "));
    CHECK(val(txt, "llb_time_to_first_token_seconds_count ") == 2, "ttft count");
    CHECK(near(val(txt, "llb_time_to_first_token_seconds_sum "), .1875), "ttft sum");
    CHECK(isnan(val(txt, "llb_spec_acceptance_ratio ")) && line(txt, "llb_spec_acceptance_ratio NaN"), "spec NaN when none drafted");
    CHECK(val(txt, "llb_requests_in_flight ") == 0, "in flight back to 0");
    // every non-comment line is "name{labels} value" or "name value"; every family has HELP+TYPE
    int bad = 0, types = 0;
    for (char *p = txt; *p;) {
        char *e = strchr(p, '\n');
        if (!e) { bad++; break; }
        if (!strncmp(p, "# TYPE ", 7)) types++;
        else if (*p != '#') {
            char *sp = memchr(p, ' ', (size_t)(e - p));
            if (!sp || sp == p) bad++;
        }
        p = e + 1;
    }
    CHECK(!bad && types >= 20, "exposition shape: bad %d types %d", bad, types);
    free(txt);
}

static void t_window_wrap(void) {
    llb_metrics_reset();
    double base = llb_now() - 1000;
    // 1500 requests, each one ITL; ITL i = i ms -> window keeps the last 1024: 477..1500 ms
    for (int i = 1; i <= 1500; i++) {
        double t[] = {.001, .001 + i * 1e-3};
        fake(base + i, 0, t, 2, 1, 0, "ok");
    }
    char *txt = llb_metrics_render(NULL);
    CHECK(val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"count\"} ") == 1024, "window count");
    // numpy: percentile(arange(477,1501)/1000, 50) = 0.9885
    CHECK(fabs(val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.5\"} ") - .9885) < 1e-9, "window p50 %.17g",
          val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.5\"} "));
    CHECK(fabs(val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.99\"} ") - 1.48977) < 1e-9, "window p99 %.17g",
          val(txt, "llb_latency_window{metric=\"itl_seconds\",quantile=\"0.99\"} "));
    CHECK(val(txt, "llb_inter_token_latency_seconds_count ") == 1500, "histogram keeps all");
    free(txt);
}

static void t_timings(void) {
    llb_req r;
    llb_req_begin(&r);
    double b = r.t_arrive;
    r.t_start = b + .010;
    r.prompt_n = 50;
    r.cached_n = 10;
    double t[] = {.210, .230, .250, .270, .290};
    for (int i = 0; i < 5; i++) llb_req_token_at(&r, b + t[i]);
    llb_req_spec(&r, 6, 4);
    llb_req_end(&r, "generate", "ok");
    r.t_end = b + .300;   // pin for exact text
    char s[1024];
    int k = llb_req_timings_json(&r, s, sizeof s);
    const char *want = "{\"cache_n\":10,\"prompt_n\":40,\"prompt_ms\":200.000,\"prompt_per_token_ms\":5.000,\"prompt_per_second\":200.000,"
                       "\"predicted_n\":5,\"predicted_ms\":80.000,\"predicted_per_token_ms\":20.000,\"predicted_per_second\":50.000,"
                       "\"ttft_ms\":210.000,\"queue_ms\":10.000,\"total_ms\":300.000,\"draft_n\":6,\"draft_n_accepted\":4}";
    CHECK(k == (int)strlen(s) && !strcmp(s, want), "timings json:\n got %s\nwant %s", s, want);
    char *txt = llb_metrics_render(NULL);
    CHECK(fabs(val(txt, "llb_spec_acceptance_ratio ") - 4.0 / 6) < 1e-9, "spec ratio");
    free(txt);
}

int main(void) {
    t_percentile();
    t_aggregates();
    t_window_wrap();
    t_timings();
    printf("%s: %d/%d checks passed\n", fails ? "FAIL" : "PASS", checks - fails, checks);
    return fails != 0;
}
