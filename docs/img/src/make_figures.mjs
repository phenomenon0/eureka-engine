// ---------- projection kernel (iso-figure) ----------
const C = Math.cos(Math.PI / 6), S = Math.sin(Math.PI / 6);
const n2 = v => String(Math.round(v * 100) / 100);
const n4 = v => String(Math.round(v * 10000) / 10000);
function kernel(OX, OY) {
  const P = (x, y, z) => [(x - y) * C + OX, (x + y) * S - z + OY];
  const D = (x, y, z) => [(x - y) * C, (x + y) * S - z];
  const plane = (O, U, V) => { const o = P(...O), u = D(...U), v = D(...V);
    return `matrix(${[u[0], u[1], v[0], v[1], o[0], o[1]].map(n4).join(' ')})`; };
  const TOP = (x, y, z) => plane([x, y, z], [1, 0, 0], [0, 1, 0]);
  const FRONT = (x, y, z) => plane([x, y, z], [1, 0, 0], [0, 0, -1]);  // y = max face, lower-left
  const SIDE = (x, y, z) => plane([x, y, z], [0, -1, 0], [0, 0, -1]);  // x = max face, lower-right
  const rect = (t, w, h, r = 0, cls = 'f') => `<rect transform="${t}" class="${cls}" width="${n2(w)}" height="${n2(h)}"${r ? ` rx="${r}"` : ''}/>`;
  const d3 = pts => 'M' + pts.map(p => P(...p).map(n2).join(' ')).join('L');
  const rounded = (x, y, z, w, d, h, r, cls) => {
    r = Math.min(r, w / 2, d / 2);
    const n = 8, z1 = z + h, q = Math.PI / 4, H = Math.PI / 2;
    const arc = (cx, cy, a0, a1) => { const o = []; for (let i = 0; i <= n; i++) { const a = a0 + (a1 - a0) * i / n; o.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); } return o; };
    const ring = [...arc(x + w - r, y + r, -H, 0), ...arc(x + w - r, y + d - r, 0, H), ...arc(x + r, y + d - r, H, 2 * H), ...arc(x + r, y + r, 2 * H, 3 * H)];
    const vis = [...arc(x + w - r, y + r, -q, 0), ...arc(x + w - r, y + d - r, 0, H), ...arc(x + r, y + d - r, H, 3 * q)];
    const wall = [...vis.map(([a, b]) => [a, b, z]), ...vis.slice().reverse().map(([a, b]) => [a, b, z1])];
    const [cs, ct] = cls;
    return `<path class="${cs}" d="${d3(wall)}Z"/><path class="${ct}" d="${d3(ring.map(([a, b]) => [a, b, z1]))}Z"/>`;
  };
  // box: three visible faces, back to front. cls = [side, front, top] classes.
  const box = (x, y, z, w, d, h, r = 0, cls = ['f', 'f', 'f t']) => r > 0 ? rounded(x, y, z, w, d, h, r, [cls[1], cls[2]]) :
    rect(SIDE(x + w, y + d, z + h), d, h, 0, cls[0]) + rect(FRONT(x, y + d, z + h), w, h, 0, cls[1]) + rect(TOP(x, y, z + h), w, d, 0, cls[2]);
  const path = pts => d3(pts);
  return { P, D, plane, TOP, FRONT, SIDE, rect, box, path };
}
const LIT = ['f lit-s', 'f lit-f', 'f lit-t'];
const slits = (a0, a1, step, b0, b1, vertical = true, cls = 'dt') => {
  let s = ''; for (let a = a0; a <= a1 + 1e-6; a += step)
    s += vertical ? `<line class="${cls}" x1="${n2(a)}" y1="${b0}" x2="${n2(a)}" y2="${b1}"/>` : `<line class="${cls}" x1="${b0}" y1="${n2(a)}" x2="${b1}" y2="${n2(a)}"/>`;
  return s;
};
const on = (t, inner) => `<g transform="${t}">${inner}</g>`;

